"""Data generation and spatial resampling for the GWFRN main simulation.

The 30 by 30 and 40 by 40 lattices are used by the main experiment. The response is
generated from latent curves; every fitted method receives noisy curves.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Literal

import numpy as np
from numpy.typing import NDArray
from scipy.interpolate import BSpline


FloatArray = NDArray[np.float64]
IntArray = NDArray[np.int64]
ModelName = Literal["model1", "model3"]
ErrorName = Literal["normal", "student_t", "bimodal"]

M = 40
N = M * M
N_T = 100
T_GRID = np.linspace(0.0, 1.0, N_T)
DELTA_T = 1.0 / (N_T - 1)
QUAD_WEIGHTS = np.full(N_T, DELTA_T, dtype=np.float64)
QUAD_WEIGHTS[[0, -1]] *= 0.5
MODEL_NAMES: tuple[ModelName, ...] = (
    "model1", "model3"
)
ERROR_NAMES: tuple[ErrorName, ...] = ("normal", "student_t", "bimodal")
ANALYSIS_BASIS_DIM = 15
ANALYSIS_INTERIOR_KNOTS = tuple(np.linspace(0.0, 1.0, 13)[1:-1])


@dataclass(frozen=True)
class SimulationData:
    coords: FloatArray
    x: FloatArray
    latent_x: FloatArray
    bspline_coef: FloatArray
    z: FloatArray
    y: FloatArray
    mu: FloatArray
    eta: FloatArray
    zeta: FloatArray
    interaction_kappa: float
    block_ids: IntArray
    model_idx: IntArray
    test_idx: IntArray
    cv_folds: tuple[tuple[IntArray, IntArray], ...]
    seed: int
    model: str
    error: str


def _open_cubic_bspline_basis(interior_knots: tuple[float, ...]) -> FloatArray:
    """Evaluate the complete open cubic B-spline basis on ``T_GRID``."""

    degree = 3
    knots = np.r_[np.zeros(degree + 1), interior_knots, np.ones(degree + 1)]
    n_basis = len(knots) - degree - 1
    basis = np.empty((N_T, n_basis), dtype=np.float64)
    for k in range(n_basis):
        coefficient = np.zeros(n_basis)
        coefficient[k] = 1.0
        basis[:, k] = BSpline(knots, coefficient, degree, extrapolate=False)(T_GRID)
    return basis


def _raw_fourier_basis(six: bool = True) -> FloatArray:
    raw = np.column_stack(
        [
            np.ones(N_T),
            np.sqrt(2.0) * np.sin(2.0 * np.pi * T_GRID),
            np.sqrt(2.0) * np.cos(2.0 * np.pi * T_GRID),
            np.sqrt(2.0) * np.sin(4.0 * np.pi * T_GRID),
            np.sqrt(2.0) * np.cos(4.0 * np.pi * T_GRID),
            np.sqrt(2.0) * np.sin(6.0 * np.pi * T_GRID),
        ]
    )
    return raw if six else raw[:, :3]


def orthonormal_fourier_basis(six: bool = True) -> FloatArray:
    """Return a discrete-quadrature orthonormal Fourier basis.

    The first three raw functions equal the basis used for the true spatially
    varying coefficient functions. Three additional harmonics are retained
    for diagnostics of the generating function space only; fitted models do
    not receive Fourier scores.
    """

    raw = _raw_fourier_basis(six=six)
    # Orthonormalise under the same trapezoidal quadrature used below.
    q, r = np.linalg.qr(np.sqrt(QUAD_WEIGHTS)[:, None] * raw, mode="reduced")
    sign = np.where(np.diag(r) < 0.0, -1.0, 1.0)
    return q * sign[np.newaxis, :] / np.sqrt(QUAD_WEIGHTS)[:, None]

def analysis_bspline_basis() -> FloatArray:
    """Quadrature-orthonormalised 15-dimensional cubic B-spline basis.

    The underlying space is generated by open cubic B-splines with 11 equally
    spaced interior knots. A symmetric inverse square root of their Gram
    matrix provides an orthonormal coordinate system under the same
    trapezoidal inner product used throughout the simulation.
    """

    raw = _open_cubic_bspline_basis(ANALYSIS_INTERIOR_KNOTS)
    gram = raw.T @ (raw * QUAD_WEIGHTS[:, None])
    eigenvalue, eigenvector = np.linalg.eigh(gram)
    inverse_root = (eigenvector / np.sqrt(eigenvalue)) @ eigenvector.T
    return raw @ inverse_root


def analysis_bspline_roughness() -> FloatArray:
    """Return the trace-normalised second-derivative roughness matrix.

    If ``beta(t) = sum_m c_m phi_m(t)``, this matrix satisfies
    ``c.T @ Omega @ c = integral beta''(t)^2 dt / (trace(Omega0) / M)``, where
    ``Omega0`` is the unnormalised roughness matrix. This fixed normalisation
    makes the curvature-penalty grid interpretable without altering which coefficient
    functions are preferred for a given positive penalty multiplier.
    """

    degree = 3
    knots = np.r_[
        np.zeros(degree + 1),
        ANALYSIS_INTERIOR_KNOTS,
        np.ones(degree + 1),
    ]
    raw = _open_cubic_bspline_basis(ANALYSIS_INTERIOR_KNOTS)
    gram = raw.T @ (raw * QUAD_WEIGHTS[:, None])
    eigenvalue, eigenvector = np.linalg.eigh(gram)
    inverse_root = (eigenvector / np.sqrt(eigenvalue)) @ eigenvector.T
    raw_second = np.empty((N_T, ANALYSIS_BASIS_DIM), dtype=np.float64)
    for k in range(ANALYSIS_BASIS_DIM):
        coefficient = np.zeros(ANALYSIS_BASIS_DIM)
        coefficient[k] = 1.0
        spline = BSpline(knots, coefficient, degree, extrapolate=False)
        raw_second[:, k] = spline.derivative(2)(T_GRID)
    second = raw_second @ inverse_root
    roughness = second.T @ (second * QUAD_WEIGHTS[:, None])
    roughness = 0.5 * (roughness + roughness.T)
    return roughness / (np.trace(roughness) / ANALYSIS_BASIS_DIM)


def bspline_coefficients(x: FloatArray) -> FloatArray:
    """Project observed curves onto the common 15-dimensional B-spline basis.

    Coefficients minimise the trapezoidally weighted squared reconstruction
    error. They are the fixed vector inputs used by GWR, MGWR, SGWR, GNNWR,
    SANNWR, and GWANN. The response is never used in this projection.
    """

    basis = analysis_bspline_basis()
    weighted_basis = QUAD_WEIGHTS[:, None] * basis
    coefficient = np.einsum("npt,tm->npm", x, weighted_basis, optimize=True)
    return coefficient.reshape(len(x), -1)


def functional_integrals(x: FloatArray) -> FloatArray:
    """Fixed integrals used by the trainable functional first layer.

    The coefficient functions are represented by 15 cubic B-splines. Learning
    a linear combination of these integrals is
    algebraically identical to learning the spline coefficients of each
    functional neuron.
    """

    basis = analysis_bspline_basis()
    integral = np.einsum("npt,t,tk->npk", x, QUAD_WEIGHTS, basis)
    return integral.reshape(len(x), -1)


def _spatial_blocks(
    rng: np.random.Generator, inner_folds: int = 5
) -> tuple[IntArray, IntArray, IntArray, tuple]:
    """Create the fixed outer holdout and disjoint inner spatial folds."""

    if inner_folds not in (5, 9):
        raise ValueError("inner_folds must be 5 (production) or 9 (legacy pilot)")

    row = np.repeat(np.arange(M), M)
    col = np.tile(np.arange(M), M)
    block_width = M // 10
    block_ids = (10 * (row // block_width) + col // block_width).astype(np.int64)
    order = rng.permutation(100)
    model_blocks = order[:90]
    test_blocks = order[90:]
    model_idx = np.flatnonzero(np.isin(block_ids, model_blocks)).astype(np.int64)
    test_idx = np.flatnonzero(np.isin(block_ids, test_blocks)).astype(np.int64)
    folds: list[tuple[IntArray, IntArray]] = []
    blocks_per_fold = 90 // inner_folds
    for fold in range(inner_folds):
        validation_blocks = model_blocks[
            blocks_per_fold * fold : blocks_per_fold * (fold + 1)
        ]
        training_blocks = np.setdiff1d(model_blocks, validation_blocks, assume_unique=True)
        train_idx = np.flatnonzero(np.isin(block_ids, training_blocks)).astype(np.int64)
        validation_idx = np.flatnonzero(np.isin(block_ids, validation_blocks)).astype(np.int64)
        folds.append((train_idx, validation_idx))
    return block_ids, model_idx, test_idx, tuple(folds)




def generate_data(
    run_id: int,
    model: ModelName,
    error: ErrorName,
    *,
    kappa: float = 1.0,
    inner_folds: int = 5,
    m: int = 40,
) -> SimulationData:
    """Generate one reproducible m by m simulation dataset.

    Predictor streams and block allocations are shared across response
    scenarios within a replication, including alternative nonlinear-model kappa
    values.
    Response-error streams are independent across the three error
    laws. No theoretical-variance standardisation is applied to the
    functional or scalar indices.
    """

    global M, N
    if m not in (30, 40):
        raise ValueError("The main experiment permits m=30 or m=40")
    M, N = int(m), int(m) ** 2
    if run_id < 0:
        raise ValueError("run_id must be non-negative")
    if model not in MODEL_NAMES:
        raise ValueError(f"model must be one of {MODEL_NAMES}")
    if error not in ERROR_NAMES:
        raise ValueError(f"error must be one of {ERROR_NAMES}")
    if not np.isfinite(kappa) or kappa < 0.0:
        raise ValueError("kappa must be finite and non-negative")
    if model != "model3" and kappa != 1.0:
        raise ValueError(
            "A non-unit kappa is defined only for the nonlinear model "
            "(internal key model3)"
        )
    seed = 618 + 1_000_000 * int(run_id)
    streams = [np.random.default_rng(s) for s in np.random.SeedSequence([seed, M]).spawn(7)]
    rng_curve, rng_measure, rng_z, rng_normal, rng_student, rng_bimodal, rng_split = streams

    axis = np.linspace(0.0, 10.0, M)
    coords = np.column_stack((np.tile(axis, M), np.repeat(axis, M)))

    # Two latent functional predictors, each generated by six correlated
    # cubic B-spline coefficients.  Only the noisy sampled curves are observed.
    index6 = np.arange(6)
    sigma_x = 0.5 ** np.abs(index6[:, None] - index6[None, :])
    predictor_scale = 1.5
    coefficient = (
        predictor_scale
        * rng_curve.standard_normal((N, 2, 6))
        @ np.linalg.cholesky(sigma_x).T
    )
    generating_basis = _open_cubic_bspline_basis((1.0 / 3.0, 2.0 / 3.0))
    latent_x = np.einsum("npk,tk->npt", coefficient, generating_basis)
    x = latent_x + rng_measure.normal(0.0, 0.5, size=latent_x.shape)
    # This response-free projection is the common 15-dimensional analysis
    # representation supplied to every fitted method.  It is stored once to
    # avoid recomputing the same projection throughout spatial CV.
    x_bspline_coef = bspline_coefficients(x)

    index3 = np.arange(3)
    sigma_z = 0.5 ** np.abs(index3[:, None] - index3[None, :])
    z = predictor_scale * rng_z.standard_normal((N, 3)) @ np.linalg.cholesky(sigma_z).T

    u, v = coords.T
    h1 = np.sin(np.pi * u / 10.0) * np.cos(np.pi * v / 10.0)
    h2 = np.cos(np.pi * u / 5.0)
    h3 = np.sin(np.pi * v / 5.0)
    c1 = np.column_stack(
        (
            1.0 + 1.0 * h1,
            0.7 + 0.8 * h2,
            -0.5 + 0.6 * h3,
        )
    )
    c2 = np.column_stack(
        (
            -0.8 + 0.9 * h2,
            0.6 - 0.6 * h3,
            0.4 + 0.8 * h1,
        )
    )
    gamma = np.column_stack(
        (
            0.8 + 0.6 * h1,
            -0.6 + 0.5 * h2,
            0.5 - 0.5 * h3,
        )
    )

    c1_used, c2_used, gamma_used = c1, c2, gamma

    true_basis = _raw_fourier_basis(six=False)
    beta1 = c1_used @ true_basis.T
    beta2 = c2_used @ true_basis.T
    eta1 = np.sum(latent_x[:, 0] * beta1 * QUAD_WEIGHTS, axis=1)
    eta2 = np.sum(latent_x[:, 1] * beta2 * QUAD_WEIGHTS, axis=1)
    eta = np.column_stack((eta1, eta2))
    zeta = np.sum(gamma_used * z, axis=1)

    f1 = 2.0 * eta1**2 / (1.0 + eta1**2) - 1.0
    f2 = np.sin(eta2)
    f3 = np.tanh(zeta)
    if model == "model1":
        mu = eta1 + eta2 + zeta
    else:
        interaction = f1 * f2 + f1 * f3 + f2 * f3
        mu = f1 + f2 + f3 + kappa * interaction

    if error == "normal":
        epsilon = rng_normal.normal(0.0, 0.5, N)
    elif error == "student_t":
        epsilon = (0.5 / np.sqrt(3.0)) * rng_student.standard_t(df=3, size=N)
    else:
        sign = 2.0 * rng_bimodal.integers(0, 2, size=N) - 1.0
        epsilon = 0.4 * sign + rng_bimodal.normal(0.0, 0.3, N)

    block_ids, model_idx, test_idx, folds = _spatial_blocks(rng_split, inner_folds)
    return SimulationData(
        coords=coords,
        x=x,
        latent_x=latent_x,
        bspline_coef=x_bspline_coef,
        z=z,
        y=mu + epsilon,
        mu=mu,
        eta=eta,
        zeta=zeta,
        interaction_kappa=float(kappa),
        block_ids=block_ids,
        model_idx=model_idx,
        test_idx=test_idx,
        cv_folds=folds,
        seed=seed,
        model=model,
        error=error,
    )


def pairwise_euclidean(left: FloatArray, right: FloatArray) -> FloatArray:
    squared = np.sum(left * left, axis=1)[:, None] + np.sum(right * right, axis=1)[None, :]
    squared -= 2.0 * left @ right.T
    np.maximum(squared, 0.0, out=squared)
    return np.sqrt(squared)


def distance_components(
    data: SimulationData,
    left_idx: IntArray,
    right_idx: IntArray,
    *,
    covariate_subset: tuple[str, ...] = ("x1", "x2", "z"),
    functional_scales: FloatArray | None = None,
    scalar_scales: FloatArray | None = None,
) -> tuple[FloatArray, FloatArray]:
    """Return geographical and scale-balanced covariate distances.

    Each functional predictor contributes the mean-domain L2 distance between
    its projections onto the common orthonormalised M=15 B-spline space,
    divided by a training-sample scale. Each scalar predictor contributes its
    absolute difference divided by a training-sample scale. The functional and
    scalar blocks are aggregated by root mean squares and then weighted
    equally. Scale values must be estimated from the fitting observations via
    :func:`covariate_distance_scales` and reused for held-out locations.
    """

    geographic = pairwise_euclidean(data.coords[left_idx], data.coords[right_idx])
    functional_distances: list[FloatArray] = []
    # L2 distances are computed between the curves projected onto the same
    # 15-dimensional B-spline space used by all fitted models. If a(t)=B(t)c,
    # then ||a_i-a_r||_L2 equals the Euclidean distance between c_i L and c_r L,
    # where G=int B(t)B(t)^T dt=L L^T is the B-spline Gram matrix.
    basis = analysis_bspline_basis()
    gram = basis.T @ (basis * QUAD_WEIGHTS[:, None])
    chol = np.linalg.cholesky(gram)
    coefficient = data.bspline_coef.reshape(len(data.x), data.x.shape[1], -1)
    transformed = coefficient @ chol
    selected_functional: list[int] = []
    if "x1" in covariate_subset:
        selected_functional.append(0)
    if "x2" in covariate_subset:
        selected_functional.append(1)
    if selected_functional:
        if functional_scales is None:
            raise ValueError("functional_scales must be estimated from fitting data")
        if len(functional_scales) != len(selected_functional):
            raise ValueError("functional_scales has incompatible length")
        domain_length = max(float(T_GRID[-1] - T_GRID[0]), 1e-12)
        for position, j in enumerate(selected_functional):
            distance = pairwise_euclidean(
                transformed[left_idx, j], transformed[right_idx, j]
            ) / np.sqrt(domain_length)
            functional_distances.append(distance / functional_scales[position])

    scalar_distances: list[FloatArray] = []
    if "z" in covariate_subset:
        if scalar_scales is None:
            raise ValueError("scalar_scales must be estimated from fitting data")
        if len(scalar_scales) != data.z.shape[1]:
            raise ValueError("scalar_scales has incompatible length")
        for k in range(data.z.shape[1]):
            scalar_distances.append(
                np.abs(
                    data.z[left_idx, k, None] - data.z[right_idx, k][None, :]
                ) / scalar_scales[k]
            )

    blocks: list[FloatArray] = []
    if functional_distances:
        blocks.append(
            np.sqrt(np.mean(np.square(np.stack(functional_distances)), axis=0))
        )
    if scalar_distances:
        blocks.append(np.sqrt(np.mean(np.square(np.stack(scalar_distances)), axis=0)))
    if not blocks:
        raise ValueError("covariate_subset must contain at least one component")
    covariate = np.mean(np.stack(blocks), axis=0)
    same = left_idx[:, None] == right_idx[None, :]
    geographic[same] = 0.0
    covariate[same] = 0.0
    return geographic, covariate


def _positive_median(values: FloatArray) -> float:
    positive = values[values > 1e-12]
    if positive.size == 0:
        return 1.0
    return max(float(np.median(positive)), 1e-12)


def covariate_distance_scales(
    data: SimulationData,
    fit_idx: IntArray,
    *,
    covariate_subset: tuple[str, ...] = ("x1", "x2", "z"),
) -> tuple[FloatArray, FloatArray]:
    """Estimate projected-curve and scalar distance scales from fitting data only."""

    basis = analysis_bspline_basis()
    gram = basis.T @ (basis * QUAD_WEIGHTS[:, None])
    chol = np.linalg.cholesky(gram)
    coefficient = data.bspline_coef.reshape(len(data.x), data.x.shape[1], -1)
    transformed = coefficient @ chol
    domain_length = max(float(T_GRID[-1] - T_GRID[0]), 1e-12)
    functional: list[float] = []
    for label, j in (("x1", 0), ("x2", 1)):
        if label in covariate_subset:
            distance = pairwise_euclidean(
                transformed[fit_idx, j], transformed[fit_idx, j]
            ) / np.sqrt(domain_length)
            functional.append(_positive_median(distance))
    scalar: list[float] = []
    if "z" in covariate_subset:
        for k in range(data.z.shape[1]):
            difference = np.abs(
                data.z[fit_idx, k, None] - data.z[fit_idx, k][None, :]
            )
            scalar.append(_positive_median(difference))
    return np.asarray(functional, dtype=np.float64), np.asarray(scalar, dtype=np.float64)
