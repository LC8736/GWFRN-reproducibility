"""Draw Figures 2--3 from raw county coverage and refitted OOF errors.

Figure 2: observed-year counts, computed without fitting any model.
Figure 3: take |log(Y)-predicted log(Y)| for each held-out county-year, then
average within each county; map six spatial methods on one colour scale.
The plotting source is a numeric table generated by tools/build_findings.py,
not a stored image, screenshot or manually copied result panel.
"""
from pathlib import Path
import argparse
import json
import matplotlib as mpl
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
from map_common import ROOT, OUT, geography, plot_base, save

METHODS = ("GWFRN", "SGWFRN", "GNNWR", "SANNWR", "GWR", "SGWR")
FINDINGS = ROOT / "generated/findings"


def coverage():
    source = pd.read_csv(ROOT / "generated/data/county_coverage.csv", dtype={"CountyI": str})
    counties, states, mapped = geography(source)
    fig, ax = plt.subplots(figsize=(7.5, 5.2))
    fig.subplots_adjust(left=0.04, right=0.96, top=0.86, bottom=0.18)
    norm = mpl.colors.Normalize(vmin=5, vmax=20)
    cmap = mpl.colormaps["cividis"]
    plot_base(ax, counties, states, mapped, "n_years", cmap, norm)
    ax.set_title("Number of observed years during 1999-2018 (n=403)", pad=8, fontsize=11)
    cax = fig.add_axes([0.25, 0.09, 0.50, 0.035])
    cb = fig.colorbar(mpl.cm.ScalarMappable(norm=norm, cmap=cmap), cax=cax,
                      orientation="horizontal", ticks=[5, 10, 15, 20])
    cb.set_label("Number of observed years", fontsize=9)
    cb.ax.tick_params(labelsize=8, length=2)
    save(fig, "figure2_county_year_coverage")


def absolute_errors():
    source = pd.read_csv(FINDINGS / "county_mae.csv", dtype={"CountyI": str})
    # geography() reconstructs GEOIDs using the source location register.
    source = source.drop(columns=["GEOID"])
    counties, states, mapped = geography(source)
    cols = [f"{m}_mean_absolute_error_logY" for m in METHODS]
    upper = float(np.quantile(source[cols].to_numpy(dtype=float).ravel(), 0.98))
    norm = mpl.colors.Normalize(vmin=0, vmax=upper)
    cmap = mpl.colormaps["YlOrRd"]
    fig, axes = plt.subplots(3, 2, figsize=(9.4, 10.0))
    fig.subplots_adjust(left=0.008, right=0.992, top=0.965, bottom=0.09, wspace=0.015, hspace=0.10)
    means, saturated = {}, {}
    for ax, method, col in zip(axes.flat, METHODS, cols):
        plot_base(ax, counties, states, mapped, col, cmap, norm)
        means[method] = float(source[col].mean())
        saturated[method] = int((source[col] > upper).sum())
        ax.set_title(f"{method} (mean={means[method]:.3f})", pad=3)
    cax = fig.add_axes([0.20, 0.035, 0.60, 0.017])
    cb = fig.colorbar(mpl.cm.ScalarMappable(norm=norm, cmap=cmap), cax=cax,
                      orientation="horizontal", extend="max")
    cb.set_label("County mean absolute error in log yield", fontsize=9)
    cb.ax.tick_params(labelsize=8, length=2)
    save(fig, "figure3_county_mean_absolute_error")
    audit = dict(source="generated/findings/county_mae.csv", n_counties=len(source),
                 absolute_value_before_averaging=True, equal_county_means=means,
                 shared_colour_limits=[0, upper], saturated_count=saturated,
                 colour_rule="Pooled 98th percentile cap; colourbar extension denotes saturation.",
                 panel_rows=[list(METHODS[i:i+2]) for i in (0, 2, 4)])
    (OUT / "figure3_audit.json").write_text(json.dumps(audit, indent=2)+"\n", encoding="utf-8")


def main():
    global FINDINGS, OUT
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--coverage-only", action="store_true")
    parser.add_argument("--findings-dir", type=Path, default=FINDINGS)
    parser.add_argument("--figure-dir", type=Path, default=OUT)
    args = parser.parse_args()
    FINDINGS, OUT = args.findings_dir.resolve(), args.figure_dir.resolve()
    # Shared exporter and this module must use the same requested destination.
    import map_common
    map_common.OUT = OUT
    coverage()
    if not args.coverage_only:
        absolute_errors()
    print("Saved original county-polygon drawings in generated/figures/.")


if __name__ == "__main__":
    main()
